<?php

namespace App\Jobs;

use App\Models\Submitter;
use Illuminate\Bus\Queueable;
use Illuminate\Contracts\Queue\ShouldQueue;
use Illuminate\Foundation\Bus\Dispatchable;
use Illuminate\Queue\InteractsWithQueue;
use Illuminate\Queue\SerializesModels;
use Illuminate\Support\Facades\Log;
use App\Services\CompletedDocumentWriter;

class GenerateAuditTrailJob implements ShouldQueue
{
    use Dispatchable, InteractsWithQueue, Queueable, SerializesModels;

    public int $tries = 3;
    public int $timeout = 60;

    public function __construct(public readonly int $submitterId) {}

    public function handle(CompletedDocumentWriter $writer): void
    {
        $submitter = Submitter::with(['submission.template', 'submission.submitters'])
            ->findOrFail($this->submitterId);

        $submission = $submitter->submission;
        $template   = $submission->template;

        $pdf = new \TCPDF('P', 'mm', 'A4');
        $pdf->setPrintHeader(false);
        $pdf->setPrintFooter(false);
        $pdf->SetMargins(20, 20, 20);
        $pdf->AddPage();

        // Title
        $pdf->SetFont('helvetica', 'B', 16);
        $pdf->Cell(0, 10, 'Audit Trail', 0, 1, 'C');
        $pdf->Ln(2);

        // Divider
        $pdf->SetDrawColor(200, 200, 200);
        $pdf->Line(20, $pdf->GetY(), 190, $pdf->GetY());
        $pdf->Ln(4);

        // Document info
        $pdf->SetFont('helvetica', 'B', 11);
        $pdf->Cell(0, 7, 'Document Information', 0, 1);
        $pdf->SetFont('helvetica', '', 10);

        $rows = [
            ['Template',     $template?->name ?? 'N/A'],
            ['Submission ID', '#' . $submission->id],
            ['Created At',   $submission->created_at?->format('Y-m-d H:i:s') . ' UTC'],
            ['Status',       ucfirst($submission->status)],
        ];

        foreach ($rows as [$label, $value]) {
            $pdf->SetFont('helvetica', 'B', 10);
            $pdf->Cell(50, 6, $label . ':', 0, 0);
            $pdf->SetFont('helvetica', '', 10);
            $pdf->Cell(0, 6, $value, 0, 1);
        }

        $pdf->Ln(4);
        $pdf->Line(20, $pdf->GetY(), 190, $pdf->GetY());
        $pdf->Ln(4);

        // Signer activity
        $pdf->SetFont('helvetica', 'B', 11);
        $pdf->Cell(0, 7, 'Signer Activity', 0, 1);
        $pdf->Ln(2);

        foreach ($submission->submitters as $s) {
            $pdf->SetFont('helvetica', 'B', 10);
            $name = $s->name ?: ($s->email ?: ('Submitter #' . $s->id));
            $pdf->Cell(0, 7, $name, 0, 1);

            $pdf->SetFont('helvetica', '', 9);
            if ($s->email)        $pdf->Cell(0, 5, 'Email: ' . $s->email, 0, 1);
            if ($s->sent_at)      $pdf->Cell(0, 5, 'Invited:   ' . $s->sent_at->format('Y-m-d H:i:s') . ' UTC', 0, 1);
            if ($s->opened_at)    $pdf->Cell(0, 5, 'Opened:    ' . $s->opened_at->format('Y-m-d H:i:s') . ' UTC', 0, 1);
            if ($s->completed_at) $pdf->Cell(0, 5, 'Completed: ' . $s->completed_at->format('Y-m-d H:i:s') . ' UTC', 0, 1);
            if ($s->declined_at)  $pdf->Cell(0, 5, 'Declined:  ' . $s->declined_at->format('Y-m-d H:i:s') . ' UTC', 0, 1);

            $pdf->Ln(3);
        }

        $pdf->Ln(2);
        $pdf->Line(20, $pdf->GetY(), 190, $pdf->GetY());
        $pdf->Ln(4);

        // Footer note
        $pdf->SetFont('helvetica', 'I', 8);
        $pdf->SetTextColor(120, 120, 120);
        $pdf->MultiCell(0, 5,
            'This audit trail was generated by Vouch on ' . now()->format('Y-m-d H:i:s') . ' UTC. ' .
            'It serves as a record of the electronic signing process.',
            0, 'L'
        );

        $writer->write($submitter, 'audit_trail.pdf', null, $pdf->Output('', 'S'), 'audit-trail');
    }

    public function failed(\Throwable $e): void
    {
        Log::error("Audit trail generation failed for submitter {$this->submitterId}: {$e->getMessage()}");
    }
}
