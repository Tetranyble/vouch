<?php

namespace App\Http\Controllers\Public;

use App\Http\Controllers\Controller;
use App\Models\Submitter;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Cache;

/**
 * KBA (Knowledge-Based Authentication) — simple questionnaire-based identity check.
 *
 * In production this would integrate with a KBA provider (e.g., Persona, Vouched, LexisNexis).
 * This implementation provides the API surface and session tracking without requiring a third-party.
 */
class SubmitFormKbaController extends Controller
{
    public function show(string $slug)
    {
        $submitter = Submitter::where('slug', $slug)->firstOrFail();

        // Check if already verified
        if (session("kba_verified:{$slug}")) {
            return response()->json(['verified' => true]);
        }

        return response()->json([
            'verified' => false,
            'questions' => $this->getQuestions($submitter),
        ]);
    }

    public function store(Request $request, string $slug)
    {
        $request->validate(['answers' => 'required|array']);

        $submitter = Submitter::where('slug', $slug)->firstOrFail();
        $expected = Cache::get("kba_answers:{$slug}");

        if (! $expected) {
            return response()->json(['error' => 'KBA session expired. Please try again.'], 422);
        }

        $correct = 0;
        foreach ($expected as $i => $answer) {
            if (($request->input("answers.{$i}") ?? '') === $answer) {
                $correct++;
            }
        }

        // Require at least 3 out of 4 correct
        if ($correct < 3) {
            return response()->json(['error' => 'Identity verification failed. Please try again.', 'correct' => $correct], 422);
        }

        Cache::forget("kba_answers:{$slug}");
        session(["kba_verified:{$slug}" => true]);

        return response()->json(['verified' => true]);
    }

    private function getQuestions(Submitter $submitter): array
    {
        // In production, these would be generated by a KBA provider based on
        // public records for the submitter's identity.
        // For now we return a static demo set and cache the correct answers.

        $questions = [
            [
                'id' => 0,
                'text' => 'What is the name of the street you grew up on?',
                'options' => ['Oak Street', 'Elm Avenue', 'Maple Drive', 'Pine Road'],
                'answer' => 'Oak Street',
            ],
            [
                'id' => 1,
                'text' => 'Which of these cities have you lived in?',
                'options' => ['Chicago', 'Dallas', 'Phoenix', 'None of the above'],
                'answer' => 'None of the above',
            ],
            [
                'id' => 2,
                'text' => 'What was the make of your first car?',
                'options' => ['Toyota', 'Ford', 'Honda', 'Chevrolet'],
                'answer' => 'Toyota',
            ],
            [
                'id' => 3,
                'text' => 'Which of these phone numbers have you used?',
                'options' => ['555-1234', '555-5678', '555-9012', 'None of the above'],
                'answer' => 'None of the above',
            ],
        ];

        Cache::put(
            "kba_answers:{$submitter->slug}",
            collect($questions)->pluck('answer')->toArray(),
            now()->addMinutes(15)
        );

        return collect($questions)->map(fn ($q) => [
            'id' => $q['id'],
            'text' => $q['text'],
            'options' => $q['options'],
        ])->toArray();
    }
}
