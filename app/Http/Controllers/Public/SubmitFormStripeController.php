<?php

declare(strict_types=1);

namespace App\Http\Controllers\Public;

use App\Http\Controllers\Controller;
use App\Models\Submitter;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Http;

class SubmitFormStripeController extends Controller
{
    /** The price is server-owned: never trust a price/amount supplied by the signing browser. */
    public function store(Request $request, string $slug): JsonResponse
    {
        $validated = $request->validate([
            'field_uuid' => ['required', 'string', 'max:255'],
        ]);
        $submitter = Submitter::where('slug', $slug)->with('submission')->firstOrFail();
        $submission = $submitter->submission;
        abort_unless($submission && (int) $submitter->account_id === (int) $submission->account_id, 404);
        abort_if($submitter->completed_at || $submitter->declined_at || $submission->is_expired || $submission->archived_at, 422);

        $field = collect($submission->template_fields ?? [])
            ->first(fn ($f) => is_array($f) && ($f['uuid'] ?? null) === $validated['field_uuid']
                && ($f['submitter_uuid'] ?? null) === $submitter->uuid && ($f['type'] ?? null) === 'payment');
        abort_unless($field, 422, 'This signer has no such payment field.');

        $currency = strtolower((string) ($field['preferences']['currency'] ?? 'USD'));
        $price = $field['preferences']['price'] ?? null;
        abort_unless(in_array($currency, ['usd', 'eur', 'gbp'], true)
            && is_numeric($price) && (float) $price > 0, 422, 'Payment amount is not configured.');
        $cents = (int) round(((float) $price) * 100);
        abort_unless($cents >= 50 && $cents <= 99999999, 422, 'Payment amount is outside supported limits.');

        $stripeKey = config('services.stripe.secret');
        if (! is_string($stripeKey) || $stripeKey === '') {
            return response()->json(['error' => 'Stripe is not configured.'], 503);
        }

        // All hosted return URLs are generated by the application to prevent an
        // attacker from specifying an external success/cancel redirect.
        try {
            $response = Http::withToken($stripeKey)->asForm()->timeout(20)
                ->post('https://api.stripe.com/v1/checkout/sessions', [
                    'mode' => 'payment',
                    'line_items[0][price_data][currency]' => $currency,
                    'line_items[0][price_data][unit_amount]' => $cents,
                    'line_items[0][price_data][product_data][name]' => (string) ($field['name'] ?? 'Document payment'),
                    'line_items[0][quantity]' => 1,
                    'success_url' => url("/s/{$slug}?payment=success"),
                    'cancel_url' => url("/s/{$slug}?payment=cancelled"),
                    'metadata[submitter_slug]' => $slug,
                    'metadata[field_uuid]' => $validated['field_uuid'],
                    'metadata[account_id]' => $submitter->account_id,
                ]);
        } catch (\Illuminate\Http\Client\ConnectionException $error) {
            return response()->json(['error' => 'Payment provider is temporarily unreachable.'], 502);
        }

        if ($response->failed() || ! is_string($response->json('url'))) {
            return response()->json(['error' => 'Failed to create payment session.'], 502);
        }

        return response()->json(['url' => $response->json('url')]);
    }

    /** Verify Stripe's signed body and a five-minute replay window before any mutation. */
    public function webhook(Request $request): JsonResponse
    {
        $secret = config('services.stripe.webhook_secret');
        if (! is_string($secret) || $secret === '') {
            return response()->json(['error' => 'Payment webhook is not configured.'], 503);
        }

        $header = $request->header('Stripe-Signature');
        $parts = [];
        foreach (explode(',', is_string($header) ? $header : '') as $part) {
            $pair = explode('=', trim($part), 2);
            if (count($pair) === 2) {
                $parts[trim($pair[0])][] = trim($pair[1]);
            }
        }
        $timestamp = $parts['t'][0] ?? '';
        if (! ctype_digit($timestamp) || abs(now()->timestamp - (int) $timestamp) > 300) {
            return response()->json(['error' => 'Invalid Stripe signature timestamp.'], 400);
        }
        $expected = hash_hmac('sha256', $timestamp.'.'.$request->getContent(), $secret);
        $signatures = $parts['v1'] ?? [];
        if (! collect($signatures)->contains(fn ($signature) => is_string($signature)
            && strlen($signature) === 64 && hash_equals($expected, $signature))) {
            return response()->json(['error' => 'Invalid Stripe signature.'], 400);
        }

        $event = json_decode($request->getContent(), true);
        if (! is_array($event) || ! is_string($event['type'] ?? null)) {
            return response()->json(['error' => 'Invalid Stripe event payload.'], 400);
        }
        if ($event['type'] !== 'checkout.session.completed') {
            return response()->json(['received' => true]);
        }

        $session = $event['data']['object'] ?? null;
        if (! is_array($session) || ($session['payment_status'] ?? null) !== 'paid'
            || ($session['mode'] ?? null) !== 'payment') {
            return response()->json(['received' => true]);
        }

        $slug = $session['metadata']['submitter_slug'] ?? null;
        $fieldUuid = $session['metadata']['field_uuid'] ?? null;
        $accountId = $session['metadata']['account_id'] ?? null;
        $paymentIntent = $session['payment_intent'] ?? null;
        if (! is_string($slug) || ! is_string($fieldUuid) || ! is_numeric($accountId)
            || ! is_string($paymentIntent) || $paymentIntent === '') {
            return response()->json(['received' => true]);
        }

        DB::transaction(function () use ($slug, $fieldUuid, $accountId, $session, $paymentIntent): void {
            $submitter = Submitter::where('slug', $slug)->lockForUpdate()->first();
            if (! $submitter || $submitter->completed_at || $submitter->declined_at
                || (int) $submitter->account_id !== (int) $accountId) {
                return;
            }
            $submission = $submitter->submission;
            if (! $submission || (int) $submission->account_id !== (int) $accountId) {
                return;
            }

            $field = collect($submission->template_fields ?? [])->first(fn ($f) => is_array($f)
                && ($f['uuid'] ?? null) === $fieldUuid && ($f['submitter_uuid'] ?? null) === $submitter->uuid
                && ($f['type'] ?? null) === 'payment');
            if (! $field) {
                return;
            }

            $price = $field['preferences']['price'] ?? null;
            $currency = strtolower((string) ($field['preferences']['currency'] ?? 'USD'));
            if (! is_numeric($price) || (int) round(((float) $price) * 100) !== (int) ($session['amount_total'] ?? -1)
                || $currency !== strtolower((string) ($session['currency'] ?? ''))) {
                return;
            }

            $values = $submitter->values ?? [];
            if (($values[$fieldUuid] ?? null) === $paymentIntent) {
                return;
            } // Stripe retry
            // Preserve the first successful verified payment, never overwrite it
            // with a different session's payment intent.
            if (! empty($values[$fieldUuid])) {
                return;
            }
            $values[$fieldUuid] = $paymentIntent;
            $submitter->update(['values' => $values]);
        }, 3);

        return response()->json(['received' => true]);
    }
}
